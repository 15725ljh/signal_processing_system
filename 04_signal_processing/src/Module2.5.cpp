/*
 * 模块04 - 干扰识别实现 (shibie)
 *
 * 功能: 从雷达信号矩阵 Radar_Sig 中选取指定脉冲,调用 gr_detection() 进行干扰类型识别
 *       自动选择 pulse_index=0(第一个脉冲)
 *
 * 干扰类型编码(J_type):
 *   0  - 无干扰/未识别到有效干扰
 *   1  - 常规梳状谱干扰(单峰特征)
 *   2  - 规则梳状谱干扰(均匀间歇)
 *   3  - 随机梳状谱干扰(不规则间歇)
 *   4  - 频谱弥散干扰(调频率匹配且脉冲数多)
 *   5  - 灵巧噪声干扰(宽带特征,带宽比<1.5)
 *   6  - 窄带干扰(带宽比>=1.5)
 *   7  - 密集假目标干扰(调频率匹配且脉冲数少)
 *   8  - 扫频干扰(调频率不匹配)
 *   9  - 梳状谱干扰(单间歇或多脉冲特征)
 *   10 - 联合拖引干扰(单脉冲特征)
 *
 * 依赖: Module0.h, Module2.5.h(gr_detection函数)
 * 输入: 全局 Radar_Sig 矩阵(从01或02模块输出)
 */
#include "Module0.h"   // 工具函数(platform_pause等) + 全局参数
#include "Module2.5.h" // 干扰识别函数声明(shibie + gr_detection)

/* 
* J_type干扰类型标识，具体对应关系：
* 0 - 无干扰/未识别到有效干扰
* 1 - 常规梳状谱干扰(单峰特征)
* 2 - 规则梳状谱干扰(均匀间歇)
* 3 - 随机梳状谱干扰(不规则间歇)
* 4 - 频谱弥散干扰(调频率匹配且脉冲数多)
* 5 - 灵巧噪声干扰(宽带特征，带宽比<1.5)
* 6 - 窄带干扰(带宽比≥1.5)
* 7 - 密集假目标干扰(调频率匹配且脉冲数少)
* 8 - 扫频干扰(调频率不匹配)
* 9 - 梳状谱干扰(单间歇或多脉冲特征)
* 10 - 联合拖引干扰(单脉冲特征)
*/

int shibie() {
    cout << "请选择带入干扰识别模块的输入多脉冲信号脉冲号(1~nan1):" << endl;
    pulse_index = 1;
    cout << "已自动选择pulse_index=1" << endl;
    VectorXcd data = Radar_Sig.col(pulse_index-1);   // 输入Radar_Sig的第pulse_index个脉冲信号
    int J_type = gr_detection(data);                 // Radar_Sig输入,识别其中的干扰类型
    
    cout << endl << ("J_type/干扰类型: 0/无干扰/未识别到有效干扰") << endl;
    cout << ("J_type/干扰类型: 1/常规单峰梳状谱干扰  2/均匀间歇规则梳状谱干扰  3/不规则间歇随机梳状谱干扰") << endl;
    cout << ("J_type/干扰类型: 4/频谱弥散干扰(调频率匹配且脉冲数多)  5/灵巧噪声干扰(宽带特征，带宽比<1.5)  6/窄带干扰(带宽比≥1.5)") << endl;
    cout << ("J_type/干扰类型: 7/密集假目标干扰(调频率匹配且脉冲数少)  8/扫频干扰(调频率不匹配)  9/梳状谱干扰(单间歇或多脉冲特征)") << endl;
    cout << ("J_type/干扰类型: 10/联合拖引干扰(单脉冲特征)") << endl;

    cout << ("输入多脉冲信号Radar_Sig的选定脉冲的干扰识别结果 J_type = ") << J_type << endl;
    
    platform_pause();
    return 0;
}
