function tfr = tfrstft(x,t,N,h)
% 输入  复向量     实向量    整数    实向量
%       x: 输入信号的复数时域向量，长度为任意
%       t: 时间点向量，指定在哪些时间位置进行时频分析
%       N: 频率轴的点数（即FFT的长度），决定输出频谱的频率分辨率
%       h: 实数窗函数向量，用于加窗操作，通常为对称窗（如汉明窗、汉宁窗等）
% 输出  复矩阵
%       tfr: 大小为 N × length(t) 的复数矩阵，表示信号在每个时间点 t(i) 处的短时傅里叶变换结果
%            每一列对应一个时间点的频谱，行对应频率从 0 到 N-1 的离散频率点

[xrow,~] = size(x);
[~,tcol] = size(t);
[hrow,~]=size(h); Lh=(hrow-1)/2;
% h=h/norm(h); % 可选：对窗函数归一化（当前被注释）
tfr= complex(zeros (N,tcol) );

% 原始循环版本（被注释）：对每个时间点 ti，在对称区间 tau 上取信号片段与窗函数共轭相乘
% for icol=1:tcol
%     ti= t(icol); tau=-min([round(N/2)-1,Lh,ti-1]):min([round(N/2)-1,Lh,xrow-ti]);
%     indices= rem(N+tau,N)+1;
%     tfr(indices,icol)=x(ti+tau,1).*conj(h(Lh+1+tau))/2^15;
% end

% 将信号 x 和窗函数 h 零填充，在前后各补 Lh 个零，以便后续滑动窗口操作边界处理
x = [zeros(Lh,1) ;x ;zeros(Lh,1)];
h = [zeros(Lh,1) ;h ;zeros(Lh,1)];

% 滑窗计算并保存计算结果
% 对每个输出时间点 i+1（对应原始时间向量 t 中的第 i+1 个点），计算加窗后的时域乘积
for i=0:1:tcol-1 % 列编号，遍历输出矩阵的每一列（即每个时间点）
    % 计算并保存前15（h0~h14相乘的结果）个滑窗计算的结果，结果保存在第1列的第18行至第32行
    % 实际上是将窗函数的后半部分（前 Lh 点）与信号在当前位置的前部对齐
    % 将乘积累加到 tfr 的下半部分（环绕区域），为后续 FFT 做准备
    for j = 0:1:Lh-1
        tfr(N-Lh+j+1,i+1) = x((i+j+1),1) * h(Lh+j+1,1) /2^15;
    end
    % 计算并保存后16(h15~h30相乘的结果)个滑窗计算的结果,结果保存在第1列的第1行至第16行
    % 将窗函数的后半部分（从中心到末尾）与信号在当前位置的后部对齐
    % 将乘积累加到 tfr 的上半部分，构成完整的加窗信号段
    for j = Lh:1:hrow-1
        tfr(j-Lh+1,i+1) = x((i+j+1),1) * h(Lh+j+1,1) /2^15; 
    end
end

% 对每一列（即每个时间点）做 N 点 FFT，将时域加窗结果转换到频域
% 得到最终的时频表示：tfr 的每一列是对应时间点的频谱
tfr=fft(tfr,[],1);

end